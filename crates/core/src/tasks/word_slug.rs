pub(crate) fn generate_word_slug() -> String {
    let mut random = rand::rngs::OsRng;
    generate_word_slug_with(|bytes| random.fill_bytes(bytes))
}

fn generate_word_slug_with(mut fill_random: impl FnMut(&mut [u8; 4])) -> String {
    fn pick<'a>(values: &'a [&'a str], fill_random: &mut impl FnMut(&mut [u8; 4])) -> &'a str {
        let mut bytes = [0_u8; 4];
        fill_random(&mut bytes);
        values[(u32::from_be_bytes(bytes) as usize) % values.len()]
    }

    let adjective = pick(ADJECTIVES, &mut fill_random);
    let verb = pick(VERBS, &mut fill_random);
    let noun = pick(NOUNS, &mut fill_random);
    format!("{adjective}-{verb}-{noun}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use sha2::{Digest, Sha256};

    fn hex(bytes: &[u8]) -> String {
        bytes.iter().map(|byte| format!("{byte:02x}")).collect()
    }

    #[test]
    fn tables_are_bound_to_the_cc_source_snapshot() {
        assert_eq!(
            CC_WORDS_SOURCE_SHA256,
            "650479aeb1f23227aa1646d038604b52a64f3256d3c0628b90d14899695ad9e1"
        );
        assert_eq!(
            (ADJECTIVES.len(), VERBS.len(), NOUNS.len()),
            (219, 109, 409)
        );
        assert_eq!(
            (ADJECTIVES[0], VERBS[0], NOUNS[0]),
            ("abundant", "baking", "aurora")
        );
        assert_eq!(
            (
                *ADJECTIVES.last().unwrap(),
                *VERBS.last().unwrap(),
                *NOUNS.last().unwrap()
            ),
            ("virtual", "zooming", "yao")
        );
        let snapshot = ADJECTIVES
            .iter()
            .copied()
            .chain(std::iter::once("--VERBS--"))
            .chain(VERBS.iter().copied())
            .chain(std::iter::once("--NOUNS--"))
            .chain(NOUNS.iter().copied())
            .collect::<Vec<_>>()
            .join("\n");
        assert_eq!(
            hex(&Sha256::digest(snapshot.as_bytes())),
            WORD_TABLES_SHA256
        );
    }

    #[test]
    fn fixed_big_endian_random_bytes_match_cc_modulo_selection() {
        let mut zeroes = [[0_u8; 4]; 3].into_iter();
        assert_eq!(
            generate_word_slug_with(|bytes| *bytes = zeroes.next().unwrap()),
            "abundant-baking-aurora"
        );

        let mut maxes = [[0xff_u8; 4]; 3].into_iter();
        assert_eq!(
            generate_word_slug_with(|bytes| *bytes = maxes.next().unwrap()),
            "lazy-shimmying-key"
        );

        let mut lasts = [
            ((ADJECTIVES.len() - 1) as u32).to_be_bytes(),
            ((VERBS.len() - 1) as u32).to_be_bytes(),
            ((NOUNS.len() - 1) as u32).to_be_bytes(),
        ]
        .into_iter();
        assert_eq!(
            generate_word_slug_with(|bytes| *bytes = lasts.next().unwrap()),
            "virtual-zooming-yao"
        );
    }
}
