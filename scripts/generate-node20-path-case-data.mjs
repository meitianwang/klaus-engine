#!/usr/bin/env node

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const EXPECTED = Object.freeze({
  node: "20.19.4",
  v8: "11.3.244.8-node.29",
  uv: "1.46.0",
  unicode: "16.0",
  icu: "77.1",
});
const PATH_SOURCE_SHA256 = "9a1f6dec4fc945ec9d50270abc957e42bf90728b1ccb50e4c31571d3fa915f4b";

for (const [name, expected] of Object.entries(EXPECTED)) {
  if (process.versions[name] !== expected) {
    throw new Error(`pinned ${name} ${expected} required, received ${process.versions[name]}`);
  }
}
const pathSource = process.binding("natives").path.replace(/\r\n/g, "\n");
const pathHash = createHash("sha256").update(pathSource).digest("hex");
if (pathHash !== PATH_SOURCE_SHA256) {
  throw new Error(`pinned path.js ${PATH_SOURCE_SHA256} required, received ${pathHash}`);
}

const mappings = [];
const upperMappings = [];
for (let point = 0; point <= 0x10ffff; point += 1) {
  if (point >= 0xd800 && point <= 0xdfff) {
    continue;
  }
  const source = String.fromCodePoint(point);
  const lowered = source.toLowerCase();
  if (lowered !== source) {
    mappings.push([point, Array.from(lowered, (value) => value.codePointAt(0))]);
  }
  const uppered = source.toUpperCase();
  if (uppered !== source) {
    upperMappings.push([point, Array.from(uppered, (value) => value.codePointAt(0))]);
  }
}

function propertyRanges(pattern) {
  const ranges = [];
  let start = null;
  let previous = null;
  for (let point = 0; point <= 0x10ffff; point += 1) {
    if (point >= 0xd800 && point <= 0xdfff) {
      continue;
    }
    const matches = pattern.test(String.fromCodePoint(point));
    if (matches) {
      if (start === null) {
        start = point;
      } else if (previous + 1 !== point) {
        ranges.push([start, previous]);
        start = point;
      }
      previous = point;
    } else if (start !== null) {
      ranges.push([start, previous]);
      start = null;
      previous = null;
    }
  }
  if (start !== null) {
    ranges.push([start, previous]);
  }
  return ranges;
}

const cased = propertyRanges(/^\p{Cased}$/u);
const caseIgnorable = propertyRanges(/^\p{Case_Ignorable}$/u);
const hex = (value) => `0x${value.toString(16)}`;
const lines = [
  "// @generated by scripts/generate-node20-path-case-data.mjs; do not edit.",
  `// Node ${EXPECTED.node}; V8 ${EXPECTED.v8}; ICU ${EXPECTED.icu}; Unicode ${EXPECTED.unicode}.`,
  `// process.binding('natives').path SHA-256 ${PATH_SOURCE_SHA256}.`,
  "",
  "pub(super) const LOWER_MAPPINGS: &[(u32, &[u32])] = &[",
  ...mappings.map(([source, target]) =>
    `    (${hex(source)}, &[${target.map(hex).join(", ")}]),`,
  ),
  "];",
  "",
  "pub(super) const UPPER_MAPPINGS: &[(u32, &[u32])] = &[",
  ...upperMappings.map(([source, target]) =>
    `    (${hex(source)}, &[${target.map(hex).join(", ")}]),`,
  ),
  "];",
  "",
  "pub(super) const CASED_RANGES: &[(u32, u32)] = &[",
  ...cased.map(([start, end]) => `    (${hex(start)}, ${hex(end)}),`),
  "];",
  "",
  "pub(super) const CASE_IGNORABLE_RANGES: &[(u32, u32)] = &[",
  ...caseIgnorable.map(([start, end]) => `    (${hex(start)}, ${hex(end)}),`),
  "];",
];
const output = `${lines.join("\n")}\n`;
const outputIndex = process.argv.indexOf("--output");
if (outputIndex === -1) {
  process.stdout.write(output);
} else {
  const destination = process.argv[outputIndex + 1];
  if (!destination) {
    throw new Error("--output requires a destination");
  }
  writeFileSync(destination, output);
}
